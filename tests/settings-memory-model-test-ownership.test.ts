/** Real SettingsMemory + picker events; provider calls are deferred, inert substitutes. */
import assert from "node:assert/strict";
import { after, test } from "node:test";
import { JSDOM } from "jsdom";
import { act, createElement, useState } from "react";
import { createServer } from "vite";
import { defaultConfig } from "../src/config/schema.js";
import type { ModelChoice } from "../src/llm/ModelManager.js";
import type {
  DesktopMemorySettings,
  DesktopMemoryStats,
  DesktopModelConfigurationInput,
  DesktopModelConnectionTestResult
} from "../src/desktop/protocol.js";
import type { SettingsDraftContextValue } from "../src/desktop/renderer/src/components/settings/SettingsDraftContext.js";

function deferred<T>() {
  let resolve!: (value: T) => void;
  let reject!: (reason: Error) => void;
  const promise = new Promise<T>((yes, no) => { resolve = yes; reject = no; });
  return { promise, resolve, reject };
}

const models: ModelChoice[] = ["A", "B"].map((name) => ({
  alias: `model-${name}`, displayName: `Model ${name}`, provider: "provider", providerType: "openai",
  model: `model-${name}`, modelKey: `provider/model-${name}`, supportsTools: true,
  efforts: [], defaultThinking: "off", thinkingLevelMap: {}, available: true, source: "configured"
}));

const scenarios = [
  "unchanged model keeps its success",
  "settled success is retired on selection change",
  "settled failure is retired on selection change",
  "pending success is retired on selection change",
  "pending failure is retired on selection change",
  "pending rejection is retired on selection change",
  "inherited default change retires a settled result",
  "inherited default change retires a pending result",
  "fresh B test owns its result while A finishes",
  "same alias configuration change retires its result"
] as const;

const dom = new JSDOM("<div id='root'></div>", { url: "https://localhost/", pretendToBeVisual: true });
const saved = new Map<string, PropertyDescriptor | undefined>();
for (const [key, value] of Object.entries({
  window: dom.window, document: dom.window.document, navigator: dom.window.navigator,
  HTMLElement: dom.window.HTMLElement, Element: dom.window.Element, Node: dom.window.Node,
  getComputedStyle: dom.window.getComputedStyle,
  requestAnimationFrame: dom.window.requestAnimationFrame.bind(dom.window),
  cancelAnimationFrame: dom.window.cancelAnimationFrame.bind(dom.window),
  MutationObserver: dom.window.MutationObserver, IS_REACT_ACT_ENVIRONMENT: true
})) {
  saved.set(key, Object.getOwnPropertyDescriptor(globalThis, key));
  Object.defineProperty(globalThis, key, { configurable: true, value });
}
const vite = await createServer({ configFile: false, server: { middlewareMode: true, hmr: false, ws: false }, appType: "custom",
  optimizeDeps: { noDiscovery: true, entries: [] } });
const { SettingsMemory } = await vite.ssrLoadModule("/src/desktop/renderer/src/components/settings/SettingsMemory.tsx") as typeof import("../src/desktop/renderer/src/components/settings/SettingsMemory.js");
const { SettingsDraftContext } = await vite.ssrLoadModule("/src/desktop/renderer/src/components/settings/SettingsDraftContext.ts") as typeof import("../src/desktop/renderer/src/components/settings/SettingsDraftContext.js");
const { createRoot } = await import("react-dom/client");
after(async () => {
  await vite.close();
  dom.window.close();
  for (const [key, descriptor] of saved) {
    if (descriptor) Object.defineProperty(globalThis, key, descriptor);
    else Reflect.deleteProperty(globalThis, key);
  }
});

for (const scenario of scenarios) test(`memory model test: ${scenario}`, async () => {
  const root = createRoot(document.getElementById("root")!);
  const inherited = scenario.startsWith("inherited");
  const policy: DesktopMemorySettings = { ...defaultConfig.context.memory, enabled: true,
    memoryModel: inherited ? undefined : "model-A" };
  const stats: DesktopMemoryStats = { configRevision: "1", revision: 1, settings: policy, totalEntries: 0,
    memoryStats: { total: 0, autoGenerated: 0, manualAdded: 0 }, maintenance: { state: "idle", eligible: 0, processed: 0, written: 0, failed: 0 } };
  const requests: Array<{ configuration: DesktopModelConfigurationInput } & ReturnType<typeof deferred<DesktopModelConnectionTestResult>>> = [];
  const unused = async (): Promise<never> => { throw new Error("unexpected memory mutation"); };
  const props: Parameters<typeof SettingsMemory>[0] = {
    models, embeddingModels: [], workspaceAvailable: true, sessionRunning: false,
    onLoadStats: async () => stats,
    onLoadEntries: async (offset, limit) => ({ revision: 1, entries: [], total: 0, offset, limit }),
    onSearch: async () => [], onAdd: unused, onUpdate: unused, onDeleteEntry: unused, onArchiveEntry: unused,
    onLoadArchived: async (offset, limit) => ({ revision: 1, entries: [], total: 0, offset, limit }),
    onRunSleep: unused, onSleepStatus: async () => stats.maintenance, onSleepRuns: async () => [],
    onPreviewSleep: unused, onCancelSleep: unused, onClearMemory: unused,
    onTestModelConfiguration: (configuration) => {
      const request = { configuration, ...deferred<DesktopModelConnectionTestResult>() };
      requests.push(request);
      return request.promise;
    },
    onLoadEmbeddingStatus: async () => { throw new Error("embedding unavailable in model test fixture"); },
    onDownloadEmbeddingModel: unused, onCancelEmbeddingDownload: unused,
    onRebuildEmbeddingIndex: unused, onCancelEmbeddingRebuild: unused,
    onNotify: (message) => assert.fail(`unexpected notification: ${message}`)
  };
  function Harness({ resolvedToolModel = "model-A", choices = models }: { resolvedToolModel?: string; choices?: ModelChoice[] }) {
    const [memory, setMemory] = useState(policy);
    const context = { draft: { memory }, snapshot: { memory: policy, models: { connections: [], resolvedToolModel } },
      dirtyCount: memory === policy ? 0 : 1, setMemory } as unknown as SettingsDraftContextValue;
    return createElement(SettingsDraftContext.Provider, { value: context }, createElement(SettingsMemory, { ...props, models: choices }));
  }
  const card = () => document.querySelector("#memory-tool-model .connection-test-result");
  const button = () => {
    const target = document.querySelector<HTMLButtonElement>('#memory-tool-model button[aria-label="测试模型"]');
    assert.ok(target);
    return target;
  };
  const picker = () => {
    const target = document.querySelector<HTMLButtonElement>('[role="combobox"][aria-label="记忆工具模型"]');
    assert.ok(target);
    return target;
  };
  const selectB = async () => {
    assert.equal(picker().disabled, false, "model choice remains available during the old request");
    await act(async () => { picker().click(); });
    const option = [...document.querySelectorAll<HTMLButtonElement>('[role="option"]')]
      .find((item) => item.textContent?.includes("model-B"));
    assert.ok(option, "the real model picker exposes model B");
    await act(async () => { option.click(); });
    assert.match(picker().textContent ?? "", /model-B/u);
  };
  try {
    await act(async () => { root.render(createElement(Harness)); });
    await act(async () => { button().click(); });
    assert.equal(requests.length, 1);
    const first = requests[0]!;
    assert.deepEqual(first.configuration, { alias: "model-A", displayName: "Model A", providerAlias: "provider",
      providerType: "openai", model: "model-A", baseUrl: undefined, supportsTools: true, supportsThinking: false });
    assert.equal(button().disabled, true);
    assert.equal(Boolean(card()), false);
    const settled = scenario.includes("settled") || scenario.startsWith("unchanged") || scenario.startsWith("same alias");
    const failure = scenario.includes("failure");
    if (settled) {
      await act(async () => { first.resolve(failure ? { ok: false, message: "A refused" } : { ok: true, message: "A connected", latencyMs: 1200 }); });
      assert.match(card()?.textContent ?? "", failure ? /测试失败.*A refused/u : /测试通过.*1\.2 秒/u);
      assert.equal(button().disabled, false);
    }
    if (scenario.startsWith("unchanged")) {
      await act(async () => { root.render(createElement(Harness, { choices: models.map((model) => ({ ...model })) })); });
      assert.match(card()?.textContent ?? "", /测试通过.*1\.2 秒/u, "unchanged request input keeps the valid result");
      return;
    }
    if (inherited) {
      await act(async () => { root.render(createElement(Harness, { resolvedToolModel: "model-B" })); });
      assert.match(picker().textContent ?? "", /使用默认工具模型/u);
    } else if (scenario.startsWith("same alias")) {
      await act(async () => { root.render(createElement(Harness, { choices: models.map((model) =>
        model.alias === "model-A" ? { ...model, baseUrl: "https://new-endpoint.invalid/v1" } : model) })); });
    } else {
      await selectB();
    }
    assert.equal(Boolean(card()), false, "a result for A must not validate the changed model selection");
    if (scenario.startsWith("fresh B")) {
      assert.equal(button().disabled, false, "the current selection can be tested without waiting for retired A");
      await act(async () => { button().click(); });
      assert.equal(requests.length, 2);
      const second = requests[1]!;
      assert.equal(second.configuration.alias, "model-B");
      await act(async () => { first.resolve({ ok: false, message: "late A failure" }); });
      assert.equal(Boolean(card()), false);
      assert.equal(button().disabled, true, "retired A must not clear the pending state for B");
      await act(async () => { second.resolve({ ok: true, message: "B connected", latencyMs: 2400 }); });
      assert.match(card()?.textContent ?? "", /测试通过.*2\.4 秒/u);
      assert.equal(button().disabled, false);
      return;
    }
    if (!settled) {
      await act(async () => {
        if (scenario.includes("rejection")) first.reject(new Error("late A rejection"));
        else first.resolve(failure ? { ok: false, message: "late A failure" } : { ok: true, message: "A connected", latencyMs: 1200 });
      });
      assert.equal(Boolean(card()), false, "late A completion must not reappear beside the new selection");
    }
    assert.equal(button().disabled, false);
    await act(async () => { button().click(); });
    assert.equal(requests.length, 2);
    const next = requests[1]!;
    if (scenario.startsWith("same alias")) assert.equal(next.configuration.baseUrl, "https://new-endpoint.invalid/v1");
    else assert.equal(next.configuration.alias, "model-B");
    await act(async () => { next.resolve({ ok: true, message: "B connected", latencyMs: 2400 }); });
    assert.match(card()?.textContent ?? "", /测试通过.*2\.4 秒/u);
  } finally {
    await act(async () => { root.unmount(); });
  }
});
