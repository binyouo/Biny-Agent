/**
 * 记忆列表的翻页位置：增删改一条记忆后停留在当前页，不把用户丢回第一页。
 *
 * 每条记忆变更都会重新读取当前页；若省略页码时按默认值回到第 0 页，用户在第 5 页删除
 * 一条就会被弹回第一页，丢掉阅读位置。末页被删空时应回退到仍存在的最后一页，而不是
 * 停在空列表上。DOM 回归不替代视觉验收。
 */
import assert from "node:assert/strict";
import { test } from "node:test";
import { defaultConfig } from "../src/config/schema.js";
import type { DesktopMemoryArchivePage, DesktopMemoryEntriesPage, DesktopMemoryEntry, DesktopMemorySearchMatch, DesktopMemoryStats } from "../src/desktop/protocol.js";
import type { SettingsDraftContextValue } from "../src/desktop/renderer/src/components/settings/SettingsDraftContext.js";

function entry(index: number): DesktopMemoryEntry {
  return {
    id: `memory-${String(index)}`, content: `记忆条目 ${String(index)}`, importance: 0.5,
    createdAt: "2026-01-01T00:00:00.000Z", updatedAt: "2026-01-01T00:00:00.000Z",
    source: "manual", paths: [], tags: [], accessCount: 0
  } as unknown as DesktopMemoryEntry;
}

interface PendingPage<T> { result: T; resolve(result: T): void; reject(error: Error): void }
interface MemoryPanelFixture {
  state: { total: number; archiveTotal: number; label: string; deferEntries: boolean; deferArchived: boolean; deferUpdates: boolean };
  reads: string[];
  pendingEntries: PendingPage<DesktopMemoryEntriesPage>[];
  pendingArchived: PendingPage<DesktopMemoryArchivePage>[];
  searches: Array<{ query: string; resolve(matches: DesktopMemorySearchMatch[]): void; reject(error: Error): void }>;
  notifications: string[];
  updates: Array<{ content: string; result: DesktopMemoryStats; resolve(stats: DesktopMemoryStats): void }>;
  typeEditor(value: string): Promise<void>;
  typeSearch(value: string): Promise<void>;
  submitSearch(options?: { isComposing?: boolean; keyCode?: number }): Promise<void>;
  render(hidden?: boolean): Promise<void>;
  click(selector: string): Promise<void>;
  settle(action: () => void): Promise<void>;
  pageLabel(): string;
}

async function withMemoryPanel(check: (fixture: MemoryPanelFixture) => Promise<void>): Promise<void> {
  const { JSDOM } = await import("jsdom");
  const dom = new JSDOM("<div id='root'></div>", { url: "https://localhost/", pretendToBeVisual: true });
  const saved = new Map<string, PropertyDescriptor | undefined>();
  for (const [key, value] of Object.entries({
    window: dom.window, document: dom.window.document, navigator: dom.window.navigator,
    HTMLElement: dom.window.HTMLElement,
    requestAnimationFrame: dom.window.requestAnimationFrame.bind(dom.window),
    cancelAnimationFrame: dom.window.cancelAnimationFrame.bind(dom.window),
    MutationObserver: dom.window.MutationObserver,
    IS_REACT_ACT_ENVIRONMENT: true
  })) {
    saved.set(key, Object.getOwnPropertyDescriptor(globalThis, key));
    Object.defineProperty(globalThis, key, { configurable: true, value });
  }
  dom.window.confirm = () => true;
  // 轮询由独立回归保护；这里冻结周期时钟，只统计翻页与显式动作触发的读取。
  dom.window.setInterval = (() => 1) as typeof dom.window.setInterval;
  dom.window.clearInterval = () => undefined;
  const React = await import("react");
  const { act, createElement } = React;
  const { createRoot } = await import("react-dom/client");
  const { createServer } = await import("vite");
  const vite = await createServer({ configFile: false, server: { middlewareMode: true }, appType: "custom",
    optimizeDeps: { noDiscovery: true, entries: [] } });
  const { SettingsMemory } = await vite.ssrLoadModule("/src/desktop/renderer/src/components/settings/SettingsMemory.tsx") as typeof import("../src/desktop/renderer/src/components/settings/SettingsMemory.js");
  const { SettingsDraftContext } = await vite.ssrLoadModule("/src/desktop/renderer/src/components/settings/SettingsDraftContext.ts") as typeof import("../src/desktop/renderer/src/components/settings/SettingsDraftContext.js");
  const root = createRoot(document.getElementById("root")!);

  const state = { total: 120, archiveTotal: 60, label: "初始", deferEntries: false, deferArchived: false, deferUpdates: false };
  const reads: string[] = [];
  const pendingEntries: PendingPage<DesktopMemoryEntriesPage>[] = [];
  const pendingArchived: PendingPage<DesktopMemoryArchivePage>[] = [];
  const searches: MemoryPanelFixture["searches"] = [];
  const notifications: string[] = [];
  const updates: MemoryPanelFixture["updates"] = [];
  const policy = { ...defaultConfig.context.memory };
  const stats = () => ({ configRevision: "1", revision: 1, settings: policy, totalEntries: state.total,
    memoryStats: { total: state.total, autoGenerated: 0, manualAdded: state.total },
    maintenance: { state: "idle", lastRun: undefined } }) as unknown as DesktopMemoryStats;
  const props = {
    models: [], embeddingModels: [], workspaceAvailable: true, sessionRunning: false,
    onLoadStats: async () => { reads.push("stats"); return stats(); },
    onLoadEntries: async (offset: number, limit: number) => {
      reads.push(`entries:${String(offset)}`);
      const entries = Array.from({ length: Math.max(0, Math.min(limit, state.total - offset)) }, (_unused, index) => ({ ...entry(offset + index), content: `${state.label} ${String(offset + index)}` }));
      const result = { revision: 1, entries, total: state.total, offset, limit };
      if (!state.deferEntries) return result;
      return await new Promise<DesktopMemoryEntriesPage>((resolve, reject) => pendingEntries.push({ result, resolve, reject }));
    },
    onSearch: async (query: string) => await new Promise<DesktopMemorySearchMatch[]>((resolve, reject) => searches.push({ query, resolve, reject })),
    onAdd: async () => stats(),
    onUpdate: async (_id: string, patch: { content: string }) => await new Promise<DesktopMemoryStats>(resolve => {
      updates.push({ content: patch.content, result: stats(), resolve });
      if (!state.deferUpdates) resolve(stats());
    }),
    onDeleteEntry: async () => { state.total -= 1; return stats(); },
    onArchiveEntry: async () => stats(),
    onLoadArchived: async (offset: number, limit: number) => {
      reads.push(`archived:${String(offset)}`);
      const entries = Array.from({ length: Math.max(0, Math.min(limit, state.archiveTotal - offset)) }, (_unused, index) => ({ ...entry(offset + index), content: `${state.label}归档 ${String(offset + index)}`, archivedAt: "2026-01-01T00:00:00.000Z" }));
      const result = { revision: 1, entries, total: state.archiveTotal, offset, limit };
      if (!state.deferArchived) return result;
      return await new Promise<DesktopMemoryArchivePage>((resolve, reject) => pendingArchived.push({ result, resolve, reject }));
    },
    onRunSleep: async () => stats(),
    onSleepStatus: async () => { reads.push("sleep-status"); return { state: "idle", lastRun: undefined }; },
    onSleepRuns: async () => { reads.push("sleep-runs"); return []; }, onPreviewSleep: async () => ({ available: false }),
    onCancelSleep: async () => ({ cancelled: false }), onClearMemory: async () => stats(),
    onTestModelConfiguration: async () => ({ ok: false }),
    onLoadEmbeddingStatus: async () => { throw new Error("offline"); },
    onDownloadEmbeddingModel: async () => { throw new Error("unused"); },
    onCancelEmbeddingDownload: async () => { throw new Error("unused"); },
    onRebuildEmbeddingIndex: async () => { throw new Error("unused"); },
    onCancelEmbeddingRebuild: async () => { throw new Error("unused"); },
    onNotify: (message: string) => { notifications.push(message); }
  } as unknown as Parameters<typeof SettingsMemory>[0];
  const context = { draft: { memory: policy }, snapshot: { memory: policy, models: { connections: [] } }, dirtyCount: 0,
    setMemory: () => undefined } as unknown as SettingsDraftContextValue;
  const pageLabel = (): string => {
    const label = document.querySelector(".activity-memory-pagination > div > span")?.textContent?.trim();
    return label ?? "";
  };
  const render = async (hidden = false): Promise<void> => {
    await act(async () => { root.render(createElement(SettingsDraftContext.Provider, { value: context }, createElement(SettingsMemory, { ...props, hidden }))); });
  };
  const click = async (selector: string): Promise<void> => {
    const button = document.querySelector<HTMLButtonElement>(selector);
    assert.ok(button, selector);
    assert.equal(button.disabled, false, `${selector} 可以操作`);
    await act(async () => { button.click(); });
  };
  try {
    await render();
    await check({ state, reads, pendingEntries, pendingArchived, searches, notifications, updates, render, click, pageLabel,
      typeEditor: async value => {
        await act(async () => {
          const input = document.querySelector<HTMLTextAreaElement>('textarea[aria-label="编辑记忆"]')!;
          Object.getOwnPropertyDescriptor(dom.window.HTMLTextAreaElement.prototype, "value")!.set!.call(input, value);
          input.dispatchEvent(new dom.window.Event("input", { bubbles: true }));
        });
      },
      typeSearch: async value => {
        await act(async () => {
          const input = document.querySelector<HTMLInputElement>('[aria-label="搜索记忆"]')!;
          Object.getOwnPropertyDescriptor(dom.window.HTMLInputElement.prototype, "value")!.set!.call(input, value);
          input.dispatchEvent(new dom.window.Event("input", { bubbles: true }));
        });
      },
      submitSearch: async (options = {}) => {
        await act(async () => { document.querySelector('[aria-label="搜索记忆"]')!.dispatchEvent(new dom.window.KeyboardEvent("keydown", { key: "Enter", bubbles: true, ...options })); });
      },
      settle: async action => { await act(async () => { action(); }); }
    });
  } finally {
    await act(() => root.unmount());
    await vite.close();
    dom.window.close();
    for (const [key, descriptor] of saved) {
      if (descriptor) Object.defineProperty(globalThis, key, descriptor);
      else Reflect.deleteProperty(globalThis, key);
    }
  }
}

const nextPage = ".activity-memory-pagination button:last-child";
const nextArchivePage = '[aria-label="下一页归档记忆"]';
const refresh = '[aria-label="刷新记忆"]';
const remove = '#memory-list [aria-label="删除记忆"]';

const searchMatch = (excerpt: string): DesktopMemorySearchMatch => ({ ...entry(0), excerpt, score: 0.9 });

test("保存记忆期间继续编辑，旧保存成功不能关闭新草稿", async () => {
  await withMemoryPanel(async ({ state, click, typeEditor, updates, settle }) => {
    state.deferUpdates = true;
    await click('#memory-list button[aria-label="编辑记忆"]');
    await typeEditor("本次提交内容");
    await click("#memory-list .settings-primary-button");
    assert.equal(updates[0]?.content, "本次提交内容");
    await typeEditor("后来继续编辑的草稿");
    await settle(() => updates[0]!.resolve(updates[0]!.result));
    assert.equal(document.querySelector<HTMLTextAreaElement>('textarea[aria-label="编辑记忆"]')?.value, "后来继续编辑的草稿", "只结束本次提交所属的编辑");
    state.deferUpdates = false;
    await click("#memory-list .settings-primary-button");
    assert.equal(updates.at(-1)?.content, "后来继续编辑的草稿");
    assert.equal(document.querySelector('textarea[aria-label="编辑记忆"]'), null, "没有后续编辑的成功保存仍结束编辑");
  });
});

test("中文候选确认不搜索，重复 Enter 合并同一在途语义搜索", async () => {
  await withMemoryPanel(async ({ typeSearch, submitSearch, searches, settle }) => {
    await typeSearch("项目配置");
    await submitSearch({ isComposing: true });
    await submitSearch({ keyCode: 229 });
    assert.equal(searches.length, 0, "选择输入法候选不启动语义搜索或模型请求");
    await submitSearch(); await submitSearch();
    assert.equal(searches.length, 1, "同一查询尚未完成时不重复启动搜索");
    await settle(() => searches[0]!.resolve([searchMatch("最新结果")]));
    assert.match(document.querySelector(".activity-memory-search-results")?.textContent ?? "", /最新结果/u);
  });
});

test("记忆搜索只展示最新查询，清空搜索不刷新全库或让旧结果回填", async () => {
  await withMemoryPanel(async ({ typeSearch, submitSearch, searches, reads, settle }) => {
    await typeSearch("旧查询"); await submitSearch();
    await typeSearch("新查询"); await submitSearch();
    await settle(() => searches[1]!.resolve([searchMatch("新查询结果")]));
    await settle(() => searches[0]!.resolve([searchMatch("过期查询结果")]));
    const result = () => document.querySelector(".activity-memory-search-results")?.textContent ?? "";
    assert.match(result(), /新查询结果/u);
    assert.doesNotMatch(result(), /过期查询结果/u);
    await typeSearch("还未完成的查询"); await submitSearch();
    reads.length = 0;
    await typeSearch(""); await submitSearch();
    assert.deepEqual(reads, [], "清空搜索只是退出结果展示，不重读记忆库和维护状态");
    await settle(() => searches[2]!.resolve([searchMatch("清空后的旧结果")]));
    assert.equal(result(), "");
  });
});

test("编辑或隐藏后的搜索失败不打断新操作，当前失败可显式重试", async () => {
  await withMemoryPanel(async ({ typeSearch, submitSearch, searches, notifications, render, settle }) => {
    await typeSearch("旧查询"); await submitSearch();
    await typeSearch("新草稿");
    await settle(() => searches[0]!.reject(new Error("过期错误")));
    assert.deepEqual(notifications, [], "仅编辑查询也使旧请求反馈失效");
    assert.equal(document.querySelector<HTMLInputElement>('[aria-label="搜索记忆"]')?.value, "新草稿");
    await submitSearch(); await render(true);
    await settle(() => searches[1]!.reject(new Error("隐藏页错误")));
    assert.deepEqual(notifications, []);
    await render(); await submitSearch();
    await settle(() => searches[2]!.reject(new Error("当前搜索不可用")));
    assert.deepEqual(notifications, ["当前搜索不可用"]);
    await submitSearch();
    await settle(() => searches[3]!.resolve([searchMatch("重试成功")]));
    assert.match(document.querySelector(".activity-memory-search-results")?.textContent ?? "", /重试成功/u);
  });
});

test("在第 5 页删除一条记忆后仍停留在第 5 页，末页删空回退到最后一页", async () => {
  await withMemoryPanel(async ({ state, reads, click, pageLabel }) => {
    assert.equal(pageLabel(), "1 / 6");
    for (let step = 0; step < 4; step += 1) await click(nextPage);
    assert.equal(pageLabel(), "5 / 6");
    assert.ok(reads.includes("entries:80"));
    reads.length = 0;
    await click(remove);
    assert.equal(pageLabel(), "5 / 6");
    assert.deepEqual(reads, ["stats", "entries:80", "sleep-status", "sleep-runs", "archived:0"], "修改后仍刷新统计与维护投影");
    state.total = 81;
    await click(remove);
    assert.equal(state.total, 80);
    assert.equal(pageLabel(), "4 / 4");
    assert.equal(reads.at(-1), "entries:60");
  });
});

test("普通翻页只请求对应列表，显式刷新仍读取完整状态并保留两边页码", async () => {
  await withMemoryPanel(async ({ reads, click, pageLabel }) => {
    reads.length = 0;
    await click(nextPage);
    assert.deepEqual(reads, ["entries:20"], "活动列表翻页不读取全库统计、维护与归档");
    assert.equal(pageLabel(), "2 / 6");
    await click('.activity-memory-disclosure[aria-controls$="-sleep-advanced"]');
    await click('.activity-memory-disclosure[aria-controls$="-archive"]');
    reads.length = 0;
    await click(nextArchivePage);
    assert.deepEqual(reads, ["archived:25"], "归档翻页不读取活动条目或全库统计");
    assert.equal(document.querySelector(".activity-memory-archive-pagination span")?.textContent, "2 / 3");
    reads.length = 0;
    await click(refresh);
    assert.deepEqual(reads, ["stats", "entries:20", "sleep-status", "sleep-runs", "archived:25"]);
    assert.equal(pageLabel(), "2 / 6");
  });
});

test("列表在外部缩短时分页回到有效末页，只补读目标列表", async () => {
  await withMemoryPanel(async ({ state, reads, click, pageLabel }) => {
    await click(nextPage);
    state.total = 21;
    reads.length = 0;
    await click(nextPage);
    assert.deepEqual(reads, ["entries:40", "entries:20"]);
    assert.equal(pageLabel(), "2 / 2");
    await click('.activity-memory-disclosure[aria-controls$="-sleep-advanced"]');
    await click('.activity-memory-disclosure[aria-controls$="-archive"]');
    await click(nextArchivePage);
    state.archiveTotal = 26;
    reads.length = 0;
    await click(nextArchivePage);
    assert.deepEqual(reads, ["archived:50", "archived:25"]);
    assert.equal(document.querySelector(".activity-memory-archive-pagination span")?.textContent, "2 / 2");
  });
});

for (const kind of ["entries", "archived"] as const) {
  test(`${kind} 翻页迟到结果在隐藏并重新加载后不得覆盖新内容`, async () => {
    await withMemoryPanel(async ({ state, pendingEntries, pendingArchived, click, render, settle }) => {
      const archive = kind === "archived";
      if (archive) {
        await click('.activity-memory-disclosure[aria-controls$="-sleep-advanced"]');
        await click('.activity-memory-disclosure[aria-controls$="-archive"]');
        state.deferArchived = true;
      } else state.deferEntries = true;
      await click(archive ? nextArchivePage : nextPage);
      const pending = archive ? pendingArchived[0]! : pendingEntries[0]!;
      assert.ok(pending, "请求被暂缓");
      try {
        await render(true);
        state.label = "最新";
        state.deferEntries = false;
        state.deferArchived = false;
        await render(false);
        const selector = archive ? ".activity-memory-archive-list .activity-memory-entry-content p" : "#memory-list .activity-memory-entry-content p";
        const current = document.querySelector(selector)?.textContent;
        assert.ok(current?.startsWith("最新"));
        await settle(() => pending.resolve(pending.result));
        assert.equal(document.querySelector(selector)?.textContent, current, "迟到页不覆盖重开后的最新读取");
      } finally {
        await settle(() => pending.resolve(pending.result));
      }
    });
  });
}
